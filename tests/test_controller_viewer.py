"""Watchers, the activity line, richer take-over input, and the desktop preview.

The hermetic half of the VP6 additions, in the shape `test_terminals.py` set:
a Vela in controller mode on disposable data, a recording stand-in for the
browser runtime, and solid-colour PNG frames generated by the test itself, so
the composite can be checked pixel by pixel without a browser. The pieces that
need no server — the watcher count, the activity store, the step words, the
placement math — are tested directly.

What is being pinned down:

- a heartbeat counts a watcher and expires on its own; the status read reports
  counts and kinds, never ids;
- the activity line comes from the step that is really running, shows only
  while the run is working, and leaves an event trail;
- a right click and a wheel-scroll go through the same lease as every other
  person input, and windows that cannot take them refuse with a sentence;
- the full-desktop frame exists only in controller mode, only for the
  controller token, and only when switched on — and composes exactly the
  windows the per-view frame route would serve.

Nothing here needs a browser or a network. The one terminal test needs a pty
and skips where there is none, the way the terminal suite does.
"""

