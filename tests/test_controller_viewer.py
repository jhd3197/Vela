def wait_for(condition, timeout=15, interval=0.05):
    """Poll until a condition holds, for things settled by a background task."""
    deadline = time.time() + timeout
    while time.time() < deadline:
        value = condition()
        if value:
            return value
        time.sleep(interval)
    raise AssertionError("the condition never held")


def png_bytes(color, size=(1280, 800)):
    buffer = io.BytesIO()
    Image.new("RGB", size, color).save(buffer, format="PNG")
    return buffer.getvalue()


class FakeRuntime:
    """Stands in for the browser runtime: captures are solid-colour PNGs.

    Records every command so a test can say exactly what input reached the
    browser, and answers `view.capture` with a picture whose colour the test
    chose per view — which is what makes the composite checkable by pixel.
    """

    def __init__(self, frames_dir):
        self._frames_dir = Path(frames_dir)
        self._frames_dir.mkdir(parents=True, exist_ok=True)
        self.commands = []
        #: view id -> the colour its capture is filled with.
        self.colors = {}
        #: view ids whose capture fails, as a dead page's would.
        self.failing = set()
        self.running = True
        self.desktops = set()
        self.info = None
        self.on_effect_request = None
        self.on_view_notice = None

    async def command(self, name, timeout=30.0, **fields):
        self.commands.append((name, fields))
        if name == "control.take":
            return {"controlEpoch": 7}
        if name == "view.input":
            return {"after": {"url": "https://example.test/", "changed": True}}
        if name == "view.act":
            return {
                "after": {"changed": True, "navigated": False, "url": "https://example.test/"},
                "observationSpent": True,
                "notices": [],
            }
        if name == "view.observe":
            return {
                "observationId": "obs-1",
                "page": {
                    "url": "https://example.test/",
                    "title": "Example",
                    "text": "hello",
                    "controls": [
                        {"ref": "f0:e1", "role": "button", "name": "Re-run failed jobs"},
                        {"ref": "f0:e2", "role": "textbox", "name": "Search"},
                    ],
                    "dialogs": [],
                },
                "notices": [],
            }
        if name == "view.capture":
            view_id = fields["viewId"]
            if view_id in self.failing:
                raise RuntimeUnavailable("The browser is restarting.")
            data = png_bytes(self.colors.get(view_id, (200, 30, 30)))
            digest = hashlib.sha256(data).hexdigest()
            (self._frames_dir / f"{digest}.png").write_bytes(data)
            return {
                "file": f"{digest}.png",
                "digest": digest,
                "bytes": len(data),
                "width": 1280,
                "height": 800,
                "deviceScaleFactor": 1,
                "capturedAt": int(time.time() * 1000),
                "runtimeSessionId": "runtime-1",
                "controlEpoch": 7,
            }
        return {}

    async def stop(self):
        self.running = False

    def inputs(self):
        return [fields["input"] for name, fields in self.commands if name == "view.input"]

    def captures(self, view_id=None):
        return [
            fields
            for name, fields in self.commands
            if name == "view.capture" and (view_id is None or fields["viewId"] == view_id)
        ]


class WatcherUnitTests(unittest.TestCase):
    """The count, without a server: beats, refreshes, expiry and the cap."""

    def setUp(self):
        self.watchers = Watchers()

    def test_nobody_is_watching_until_somebody_beats(self):
        self.assertEqual(self.watchers.summary("d1"), {"count": 0, "kinds": {}})

    def test_a_beat_counts_and_names_its_kind(self):
        summary = self.watchers.heartbeat("d1", "w1", kind="controller")
        self.assertEqual(summary, {"count": 1, "kinds": {"controller": 1}})
        summary = self.watchers.heartbeat("d1", "w2", kind="person")
        self.assertEqual(summary, {"count": 2, "kinds": {"controller": 1, "person": 1}})

    def test_the_same_watcher_beating_again_is_still_one_watcher(self):
        self.watchers.heartbeat("d1", "w1", kind="person")
        summary = self.watchers.heartbeat("d1", "w1", kind="person")
        self.assertEqual(summary["count"], 1)

    def test_a_watcher_that_stops_beating_stops_counting(self):
        self.watchers.heartbeat("d1", "w1", kind="person")
        self.watchers.heartbeat("d1", "w2", kind="person")
        key = ("d1", "w1")
        self.watchers._all[key]["expiresAt"] = time.time() - 1
        summary = self.watchers.summary("d1")
        self.assertEqual(summary, {"count": 1, "kinds": {"person": 1}})
        self.assertNotIn(key, self.watchers._all, "an expired beat is swept, not kept")

    def test_the_cap_drops_the_watcher_closest_to_expiring(self):
        for index in range(MAX_WATCHERS_PER_DESKTOP):
            self.watchers.heartbeat("d1", f"w{index}", kind="person")
            self.watchers._all[("d1", f"w{index}")]["expiresAt"] += index
        # w0 expires soonest; a new watcher takes its place, not a seventeenth slot.
        summary = self.watchers.heartbeat("d1", "new", kind="controller")
        self.assertEqual(summary["count"], MAX_WATCHERS_PER_DESKTOP)
        self.assertNotIn(("d1", "w0"), self.watchers._all)
        self.assertIn(("d1", "new"), self.watchers._all)

    def test_watching_one_desktop_is_not_watching_another(self):
        self.watchers.heartbeat("d1", "w1", kind="person")
        self.assertEqual(self.watchers.summary("d2")["count"], 0)

    def test_a_deleted_desktop_forgets_its_watchers(self):
        self.watchers.heartbeat("d1", "w1", kind="person")
        self.watchers.drop("d1")
        self.assertEqual(self.watchers.summary("d1")["count"], 0)


class ActivityUnitTests(unittest.TestCase):
    """The line, without a server: set, read, cleared, expired."""

    def test_the_line_is_what_was_set(self):
        activity = Activity()
        record = activity.note("d1", "Running npm run dev", run_id="r1")
        self.assertEqual(record["text"], "Running npm run dev")
        self.assertEqual(activity.current("d1")["runId"], "r1")

    def test_the_line_expires_when_nothing_refreshes_it(self):
        activity = Activity()
        activity.note("d1", "Clicking", run_id="r1")
        activity._all["d1"]["at"] = time.time() - ACTIVITY_TTL_SECONDS - 1
        self.assertIsNone(activity.current("d1"))
        self.assertNotIn("d1", activity._all)

    def test_clearing_names_the_run_so_a_new_runs_line_survives(self):
        activity = Activity()
        activity.note("d1", "Clicking", run_id="r2")
        self.assertFalse(activity.clear("d1", run_id="r1"))
        self.assertIsNotNone(activity.current("d1"))
        self.assertTrue(activity.clear("d1", run_id="r2"))
        self.assertIsNone(activity.current("d1"))

    def test_a_long_line_is_clipped_not_allowed_to_become_a_paragraph(self):
        activity = Activity()
        record = activity.note("d1", "x" * 500)
        self.assertLessEqual(len(record["text"]), MAX_ACTIVITY_CHARS)


